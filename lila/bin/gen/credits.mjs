// Writes lila/public/credits.html, the body of LiGo's /credits page, from docs/credits.json (unit 9.8,
// ADR 0026 §6), so the page and the repository's own list can't drift apart.
//   node lila/bin/gen/credits.mjs          rewrite the page body
//   node lila/bin/gen/credits.mjs --check  fail if the page body is stale, if a third party named in
//                                          COPYING.md §3 matches no entry, or if a puzzle file in
//                                          tools/puzzles/data/SOURCES.md has no entry
// Plain Node, no packages. LiGo's own tooling (MIT, ADR 0006).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const read = f => readFileSync(join(root, f), 'utf8');
const out = 'lila/public/credits.html';

const esc = s =>
  String(s).replace(
    /[&<>"']/g,
    c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c],
  );

export function render(list) {
  const rows = e =>
    `      <tr>
        <td><a href="${esc(e.url)}">${esc(e.name)}</a><br><small>${esc(e.by)}</small></td>
        <td>${esc(e.what)}</td>
        <td>${esc(e.licence)}</td>
      </tr>`;
  const section = s => `  <h2>${esc(s.title)}</h2>
  <table class="slist slist-pad">
    <thead><tr><th>What</th><th>Used for</th><th>Licence</th></tr></thead>
    <tbody>
${s.entries.map(rows).join('\n')}
    </tbody>
  </table>`;
  return `<!-- Generated by lila/bin/gen/credits.mjs from docs/credits.json: edit that list, not this file. -->
<div class="credits">
  <p>LiGo is free software made almost entirely of other people's free work. Thank you to everyone below.
  The full licence details are in <a href="https://github.com/DannyOPREA/LiGo/blob/main/COPYING.md">COPYING.md</a>.</p>
${list.sections.map(section).join('\n')}
</div>
`;
}

/** Problems with the list against COPYING.md §3 and the puzzle sources; empty when all is well. */
export function problems(list, copying, sources) {
  const entries = list.sections.flatMap(s => s.entries);
  const names = entries.flatMap(e => e.copying);
  const table = copying.slice(copying.indexOf('## 3. Third-party code and assets'));
  const found = [];
  for (const line of table.split('\n')) {
    if (!line.startsWith('| ') || line.startsWith('| Component') || line.startsWith('|---')) continue;
    const component = line.split(' | ')[0].slice(2);
    if (component.startsWith('No third-party') || component.startsWith('_')) continue;
    if (!names.some(n => component.includes(n)))
      found.push(`COPYING.md §3 names a third party no credits entry covers: "${component.slice(0, 80)}"`);
  }
  for (const [, file] of sources.matchAll(/^\| `([^`]+\.json)` \|/gm))
    if (!entries.some(e => e.puzzleFile === file))
      found.push(`tools/puzzles/data/SOURCES.md lists ${file}, which no credits entry covers`);
  return found;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = JSON.parse(read('docs/credits.json'));
  const html = render(list);
  if (process.argv.includes('--check')) {
    const found = problems(list, read('COPYING.md'), read('tools/puzzles/data/SOURCES.md'));
    if (read(out) !== html) found.push(`${out} is stale: run node lila/bin/gen/credits.mjs`);
    for (const p of found) console.error(`credits: ${p}`);
    if (found.length) process.exit(1);
    console.log(
      'credits: the page matches docs/credits.json, which covers COPYING.md and the puzzle sources',
    );
  } else {
    writeFileSync(join(root, out), html);
    console.log(`credits: wrote ${out}`);
  }
}
