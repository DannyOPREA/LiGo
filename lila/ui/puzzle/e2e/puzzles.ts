export const centreThree: PuzzleJson = fromSet('18Q2Y');

/** The first point of the first right line: a move that is right, to play. */
export function rightFirst(puzzle: PuzzleJson): string {
  const n = puzzle.move_tree.branches!.find(
    b => !b.wrong_answer && (b.correct_answer || b.branches?.length),
  )!;
  return String.fromCharCode(97 + n.x, 97 + n.y);
}

/** A first move that is wrong: one whose reply is marked wrong. */
export function wrongFirst(puzzle: PuzzleJson): string {
  const n = puzzle.move_tree.branches!.find(b => b.branches?.some(r => r.wrong_answer))!;
  return String.fromCharCode(97 + n.x, 97 + n.y);
}
