// The puzzles the browser tests play: real ones from the committed set (tools/puzzles/data, as
// `JsonView.puzzleJson` sends them: goban's puzzle format plus lila's `id`, `rating`, `plays`,
// `themes`, `goal` and `source`), and the straight three in the corner that libs/board's tests use.

import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface Tree {
  x: number;
  y: number;
  branches?: Tree[];
  correct_answer?: boolean;
  wrong_answer?: boolean;
}

export interface PuzzleJson {
  id: string;
  rating: number;
  plays: number;
  themes: string[];
  goal: string;
  source: string;
  width: number;
  height: number;
  bounds: { top: number; left: number; bottom: number; right: number };
  initial_state: { black: string; white: string };
  initial_player: 'black' | 'white';
  move_tree: Tree;
  puzzle_player_move_mode: 'free';
  puzzle_opponent_move_mode: 'automatic';
}

const dataDir = join(dirname(fileURLToPath(import.meta.url)), '../../../../tools/puzzles/data');

/** A puzzle of the committed set as lila's JSON has it (`JsonView.puzzleJson`, `Puzzle.sourceLine`). */
const asLila = (found: any): PuzzleJson => ({
  id: found.id,
  rating: found.rating,
  plays: 0,
  themes: found.themes,
  goal: found.goal,
  source: `Generated by LiGo (seed ${found.provenance.seed})`,
  width: found.width,
  height: found.height,
  bounds: found.bounds,
  initial_state: found.initial_state,
  initial_player: found.initial_player,
  move_tree: found.move_tree,
  puzzle_player_move_mode: 'free',
  puzzle_opponent_move_mode: 'automatic',
});

/** Every puzzle of the committed set, in file order. */
export const allPuzzles = (): PuzzleJson[] =>
  readdirSync(dataDir)
    .filter(f => /^generated-.*\.json$/.test(f))
    .sort()
    .flatMap(file => JSON.parse(readFileSync(join(dataDir, file), 'utf8')).map(asLila));

/** A puzzle of the committed set. */
function fromSet(id: string): PuzzleJson {
  const found = allPuzzles().find(p => p.id === id);
  if (!found) throw new Error(`puzzle ${id} is not in ${dataDir}`);
  return found;
}

